export function bindControlSurfaceRefs(controlSurface) {
  for (const [key, id] of Object.entries(controlUiElementIds)) {
    ui[key] = controlSurface.element(id);
  }
  for (const [key, selector] of Object.entries(controlUiCollectionSelectors)) {
    ui[key] = controlSurface.elements(selector);
  }
  for (const key of Object.keys(inputs)) {
    inputs[key] = controlSurface.element(key);
  }
}
